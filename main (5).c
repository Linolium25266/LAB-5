#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <math.h>

int main(void) {
    // Оголошення та обов'язкова ініціалізація змінних
    int choice = -1;
    int i = 0, j = 0, n = 0, k = 0;
    long long a[100] = {0};        // основний масив цілих чисел
    long long x[10] = {0};         // перший вектор (завдання 58)
    long long y[10] = {0};         // другий вектор (завдання 58)
    long long c[20] = {0};         // об'єднаний вектор (завдання 58)
    double z[50] = {0};            // вектор z (завдання 56)
    double sum = 0.0, len = 0.0;
    long long num = 0, value = 0;
    int pos = 0, found = 0, ok = 0;

    srand((unsigned)time(NULL));

    while (choice != 0) {
        printf("\n===== Меню =====\n");
        printf("Оберіть завдання: 51, 56, 58, 77, 114, 175\n");
        printf("0 - вихід\n");
        printf("Ваш вибір: ");
        if (scanf("%d", &choice) != 1) {
            printf("Помилка введення\n");
            return 1;
        }

        switch (choice) {
        case 51:
            // Завдання 51: A[i] = A[i div 2] + A[i-1], A[0] != 0
            printf("Введіть кількість елементів N (від 1 до 40): ");
            scanf("%d", &n);
            printf("Введіть початкове значення A[0] (не нуль): ");
            scanf("%lld", &a[0]);
            if (n < 1 || n > 40) {
                printf("Завдання 51: попередження, N має бути від 1 до 40\n");
            } else if (a[0] == 0) {
                printf("Завдання 51: попередження, A[0] не може дорівнювати нулю\n");
            } else {
                for (i = 1; i < n; i++) {
                    a[i] = a[i / 2] + a[i - 1];
                }
                printf("Завдання 51: масив A:\n");
                for (i = 0; i < n; i++) {
                    printf("%lld ", a[i]);
                }
                printf("\n");
            }
            break;

        case 56:
            // Завдання 56: довжина вектора z з 50 елементів
            printf("Введіть 50 елементів вектора z: ");
            sum = 0.0;
            for (i = 0; i < 50; i++) {
                scanf("%lf", &z[i]);
                sum = sum + z[i] * z[i];
            }
            len = sqrt(sum);
            printf("Завдання 56: довжина вектора L = %.10g\n", round(len * 10000) / 10000);
            break;

        case 58:
            // Завдання 58: злиття двох впорядкованих векторів
            printf("Введіть 10 елементів вектора x (за зростанням): ");
            for (i = 0; i < 10; i++) {
                scanf("%lld", &x[i]);
            }
            printf("Введіть 10 елементів вектора y (за зростанням): ");
            for (i = 0; i < 10; i++) {
                scanf("%lld", &y[i]);
            }
            ok = 1;
            for (i = 1; i < 10; i++) {
                if (x[i] < x[i - 1] || y[i] < y[i - 1]) {
                    ok = 0;
                }
            }
            if (ok == 0) {
                printf("Завдання 58: попередження, вектори мають бути впорядковані за зростанням\n");
            } else {
                i = 0;
                j = 0;
                k = 0;
                while (i < 10 && j < 10) {
                    if (x[i] <= y[j]) {
                        c[k] = x[i];
                        i++;
                    } else {
                        c[k] = y[j];
                        j++;
                    }
                    k++;
                }
                while (i < 10) {
                    c[k] = x[i];
                    i++;
                    k++;
                }
                while (j < 10) {
                    c[k] = y[j];
                    j++;
                    k++;
                }
                printf("Завдання 58: об'єднаний вектор c:\n");
                for (i = 0; i < 20; i++) {
                    printf("%lld ", c[i]);
                }
                printf("\n");
            }
            break;

        case 77:
            // Завдання 77: чи є число, кратне 7, у послідовності, що закінчується на -1
            printf("Введіть послідовність цілих чисел (закінчується числом -1): ");
            pos = 0;
            found = 0;
            num = 0;
            scanf("%lld", &num);
            while (num != -1) {
                pos++;
                if (num % 7 == 0 && found == 0) {
                    found = pos;
                }
                scanf("%lld", &num);
            }
            if (found > 0) {
                printf("Завдання 77: так, кратне 7 число є, перше має номер %d\n", found);
            } else {
                printf("Завдання 77: чисел, кратних 7, у послідовності немає\n");
            }
            break;

        case 114:
            // Завдання 114: вставити на k-те місце квадрат суми 5-го та 10-го елементів
            printf("Введіть кількість елементів масиву n (від 10 до 99): ");
            scanf("%d", &n);
            if (n < 10 || n > 99) {
                printf("Завдання 114: попередження, n має бути від 10 до 99\n");
                break;
            }
            printf("Введіть %d елементів масиву: ", n);
            for (i = 0; i < n; i++) {
                scanf("%lld", &a[i]);
            }
            printf("Введіть місце k для вставки (від 1 до %d): ", n + 1);
            scanf("%d", &k);
            if (k < 1 || k > n + 1) {
                printf("Завдання 114: попередження, k поза межами масиву\n");
            } else {
                value = (a[4] + a[9]) * (a[4] + a[9]);
                for (i = n; i >= k; i--) {
                    a[i] = a[i - 1];
                }
                a[k - 1] = value;
                n++;
                printf("Завдання 114: вставлено %lld, новий масив:\n", value);
                for (i = 0; i < n; i++) {
                    printf("%lld ", a[i]);
                }
                printf("\n");
            }
            break;

        case 175:
            // Завдання 175: масив, сусідні елементи якого різняться не більше ніж на 10%
            printf("Введіть кількість елементів n (від 2 до 100): ");
            scanf("%d", &n);
            if (n < 2 || n > 100) {
                printf("Завдання 175: попередження, n має бути від 2 до 100\n");
            } else {
                a[0] = 100 + rand() % 101;
                for (i = 1; i < n; i++) {
                    k = (int)(a[i - 1] / 10);
                    a[i] = a[i - 1] - k + rand() % (2 * k + 1);
                }
                printf("Завдання 175: випадковий масив:\n");
                for (i = 0; i < n; i++) {
                    printf("%lld ", a[i]);
                }
                printf("\n");
                ok = 1;
                for (i = 1; i < n; i++) {
                    if (llabs(a[i] - a[i - 1]) > a[i - 1] / 10) {
                        ok = 0;
                    }
                }
                if (ok == 1) {
                    printf("Перевірка: сусідні елементи різняться не більше ніж на 10%%\n");
                } else {
                    printf("Перевірка не пройдена\n");
                }
            }
            break;

        case 0:
            printf("Вихід з програми\n");
            break;

        default:
            printf("Такого завдання немає\n");
        }
    }

    return 0;
}